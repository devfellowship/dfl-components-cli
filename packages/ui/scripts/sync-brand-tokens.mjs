#!/usr/bin/env node
// Mirror of the published DFL brand design system tokens (opt-in tokens.v2.css).
//
//   --write [--version N] [--base URL]  fetch upstream, write the mirror + brand.lock.json
//   --check                             OFFLINE: file vs header vs lock (default mode)
//   --check --online                    also compare with the published upstream
//
// Exit codes: 0 ok, 1 failed check / refused write, 2 could not verify (network).
// Node built-ins only, so CI can run it before `npm ci`.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const DEFAULT_BASE = 'https://brand.devfellowship.com';
export const MARKER = '--s-surface-page';
const PKG_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const MIRROR_REL = 'src/styles/tokens.v2.css';
export const LOCK_REL = 'brand.lock.json';

export const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
export const upstreamUrl = (base, version) => `${base.replace(/\/+$/, '')}/design-system/dfl/v${version}/tokens.css`;

export function buildHeader(url, version) {
  return `/* MIRROR of ${url} @ v${version}. GENERATED by scripts/sync-brand-tokens.mjs. Do not edit: edit the brand record and publish, then run npm run sync:brand-tokens. */\n\n`;
}

// Split a mirror file into its header line and the upstream body bytes.
export function splitMirror(buf) {
  const sep = buf.indexOf('\n\n');
  if (sep < 0) return { header: buf.toString('utf8'), body: Buffer.alloc(0) };
  return { header: buf.subarray(0, sep).toString('utf8'), body: buf.subarray(sep + 2) };
}

// Accept only a real CSS answer. A Pages miss answers 200 with HTML.
export async function fetchUpstream(url, fetchFn = fetch) {
  const res = await fetchFn(url);
  if (res.status !== 200) throw new Error(`upstream answered HTTP ${res.status} for ${url}`);
  const type = res.headers.get('content-type') ?? '';
  if (!/^text\/css/i.test(type)) throw new Error(`upstream content-type is "${type}", not text/css (${url})`);
  const bytes = Buffer.from(await res.arrayBuffer());
  if (bytes.length === 0) throw new Error(`upstream body is empty (${url})`);
  if (!bytes.toString('utf8').includes(MARKER)) throw new Error(`upstream body lacks ${MARKER} (${url})`);
  return bytes;
}

export function readLock(dir = PKG_DIR) {
  const p = resolve(dir, LOCK_REL);
  return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null;
}

// All-or-nothing: both files are staged to temp names, then renamed.
export async function writeMirror({ dir = PKG_DIR, base = DEFAULT_BASE, version, fetchFn = fetch } = {}) {
  const lock = readLock(dir);
  const v = version ?? lock?.version ?? 2;
  const url = upstreamUrl(base, v);
  const body = await fetchUpstream(url, fetchFn);
  const file = Buffer.concat([Buffer.from(buildHeader(url, v)), body]);
  const newLock = {
    brand: 'dfl',
    version: Number(v),
    files: { [MIRROR_REL]: sha256(file) },
    upstream: { url, sha256: sha256(body) },
  };
  const mirrorPath = resolve(dir, MIRROR_REL);
  const lockPath = resolve(dir, LOCK_REL);
  writeFileSync(`${mirrorPath}.tmp`, file);
  writeFileSync(`${lockPath}.tmp`, `${JSON.stringify(newLock, null, 2)}\n`);
  renameSync(`${mirrorPath}.tmp`, mirrorPath);
  renameSync(`${lockPath}.tmp`, lockPath);
  return newLock;
}

// Offline check. Returns a list of failure reasons (empty = pass).
export function checkLocal(dir = PKG_DIR) {
  const errors = [];
  const mirrorPath = resolve(dir, MIRROR_REL);
  if (!existsSync(mirrorPath)) return [`mirror file missing: ${MIRROR_REL}`];
  const buf = readFileSync(mirrorPath);
  if (buf.length === 0) return [`mirror file is empty: ${MIRROR_REL}`];
  const { header, body } = splitMirror(buf);
  if (!header.startsWith('/* MIRROR of ') || header.includes('\n')) errors.push('first line is not the MIRROR header');
  const lock = readLock(dir);
  if (!lock) return [...errors, `lock missing: ${LOCK_REL}`];
  const want = lock.files?.[MIRROR_REL];
  if (sha256(buf) !== want) errors.push(`sha256 of ${MIRROR_REL} differs from ${LOCK_REL} (file ${sha256(buf)}, lock ${want}): the mirror was edited by hand`);
  if (sha256(body) !== lock.upstream?.sha256) errors.push(`sha256 of the body differs from upstream.sha256 in ${LOCK_REL} (body ${sha256(body)}, lock ${lock.upstream?.sha256})`);
  return errors;
}

// Online check: 'ok' | 'drift' | 'unverified', with a message.
export async function checkOnline({ dir = PKG_DIR, fetchFn = fetch, retries = 3, pauseMs = 2000 } = {}) {
  const lock = readLock(dir);
  if (!lock?.upstream?.url) return { status: 'drift', message: `no upstream.url in ${LOCK_REL}` };
  let last;
  for (let i = 0; i < retries; i++) {
    try {
      const bytes = await fetchUpstream(lock.upstream.url, fetchFn);
      return sha256(bytes) === lock.upstream.sha256
        ? { status: 'ok', message: 'upstream sha256 matches the lock' }
        : { status: 'drift', message: `the published version changed or the mirror drifted (upstream ${sha256(bytes)}, lock ${lock.upstream.sha256})` };
    } catch (e) {
      last = e;
      if (i < retries - 1) await new Promise((r) => setTimeout(r, pauseMs));
    }
  }
  return { status: 'unverified', message: `could not verify: ${last?.message}` };
}

async function main(argv) {
  const arg = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : undefined; };
  if (argv.includes('--write')) {
    try {
      const lock = await writeMirror({ base: arg('--base') ?? DEFAULT_BASE, version: arg('--version') });
      console.log(`wrote ${MIRROR_REL} (v${lock.version}, sha256 ${lock.files[MIRROR_REL]}) and ${LOCK_REL}`);
      return 0;
    } catch (e) {
      console.error(`sync refused: ${e.message}`);
      return 1;
    }
  }
  const errors = checkLocal();
  if (errors.length) {
    for (const e of errors) console.error(`brand token mirror: ${e}`);
    return 1;
  }
  console.log('brand token mirror: offline check ok');
  if (argv.includes('--online')) {
    const r = await checkOnline();
    if (r.status === 'ok') { console.log(`brand token mirror: ${r.message}`); return 0; }
    console.error(`brand token mirror: ${r.message}`);
    return r.status === 'drift' ? 1 : 2;
  }
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then((c) => process.exit(c));
}
