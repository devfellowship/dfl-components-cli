#!/usr/bin/env node
/**
 * Generate `__fixtures__/long-5000.json` — the tall-map fixture.
 *
 * Round R4 renders this one in the `FixtureLong5000` story to prove that a map
 * taller than the viewport scrolls as a normal document, with no virtualisation
 * and no windowing (plan, "Responsive and long maps"). Verification row 3 counts
 * at least 200 nodes on it, so the shape below is a floor, not a suggestion.
 *
 * The generator is DETERMINISTIC: no clock, no randomness, no network. Running
 * it twice writes the same bytes, so a regenerated fixture shows an empty diff
 * unless the shape really changed.
 *
 *   node scripts/gen-roadmap-long-fixture.mjs           # writes the fixture
 *   node scripts/gen-roadmap-long-fixture.mjs --check   # fails if it is stale
 *
 * Height arithmetic (the reason for 120 rows): the R4 breakpoint table gives a
 * 49 px node box plus a 12 px row gap at every width from 360 up, so 120 rows
 * are 120 * 61 - 12 = 7 308 px of grid, plus the group padding. That clears the
 * 5 000 px target with room for the label wrap at 360 px.
 */
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "src", "components", "organisms", "roadmap", "__fixtures__", "long-5000.json");

const ROWS = 120;
const GROUP_SIZE = 20;

/** Deterministic word picks — an index, never a random number generator. */
const TOPICS = [
  "Foundations", "Syntax", "Types", "Control flow", "Functions", "Modules",
  "Collections", "Iterators", "Errors", "Testing", "Tooling", "Packaging",
  "Concurrency", "Networking", "Storage", "Caching", "Security", "Observability",
  "Performance", "Deployment",
];
const SIDES = [
  "Read the spec", "Work an exercise", "Compare two designs", "Write a summary",
  "Explain it aloud", "Find a counter-example", "Measure the cost", "Review a PR",
];
const GROUP_TONES = ["neutral", "muted", "accent", "info"];

const nodes = [];
const edges = [];
const groups = [];

nodes.push({
  id: "title",
  kind: "title",
  column: "center",
  order: 0,
  span: 3,
  label: "A very long map — 120 rows, three columns",
});

for (let row = 1; row < ROWS; row += 1) {
  const spine = `s${row}`;
  nodes.push({
    id: spine,
    kind: "topic",
    column: "center",
    order: row,
    label: `${row}. ${TOPICS[row % TOPICS.length]}`,
    ...(row % 17 === 0 ? { tone: "accent" } : {}),
  });
  if (row > 1) {
    edges.push({ id: `spine-${row}`, source: `s${row - 1}`, target: spine, style: "solid", route: "straight" });
  }
  if (row % 2 === 1) {
    const left = `l${row}`;
    nodes.push({
      id: left,
      kind: "subtopic",
      column: "left",
      order: row,
      label: SIDES[row % SIDES.length],
      ...(row % 6 === 1 ? { badge: "practice" } : {}),
    });
    edges.push({ id: `left-${row}`, source: spine, target: left, route: "elbow" });
  }
  if (row % 3 === 0) {
    const right = `r${row}`;
    nodes.push({
      id: right,
      kind: "subtopic",
      column: "right",
      order: row,
      label: `${TOPICS[(row + 7) % TOPICS.length]} in depth`,
      ...(row % 9 === 0 ? { badge: "reference" } : {}),
    });
    edges.push({ id: `right-${row}`, source: spine, target: right, route: "curve" });
  }
}

for (let start = 1; start < ROWS; start += GROUP_SIZE) {
  const end = Math.min(start + GROUP_SIZE - 1, ROWS - 1);
  const index = (start - 1) / GROUP_SIZE;
  groups.push({
    id: `g${index}`,
    title: `Part ${index + 1} — rows ${start} to ${end}`,
    tone: GROUP_TONES[index % GROUP_TONES.length],
    from: start,
    to: end,
  });
}

const document = {
  version: "roadmap/v1",
  title: "Long map — 5 000 px",
  direction: "down",
  columns: 3,
  meta: {
    source: "generated by packages/ui/scripts/gen-roadmap-long-fixture.mjs",
    note: "Deterministic. Regenerate with `node scripts/gen-roadmap-long-fixture.mjs`; verify with `--check`.",
    rows: ROWS,
  },
  legend: {
    placement: "top",
    entries: [
      { id: "practice", label: "Practice", tone: "success", icon: "check" },
      { id: "reference", label: "Reference", tone: "info", icon: "book-open" },
    ],
  },
  groups,
  nodes,
  edges,
};

const json = `${JSON.stringify(document, null, 2)}\n`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== json) {
    console.error(`STALE: ${OUT} does not match the generator. Run: node scripts/gen-roadmap-long-fixture.mjs`);
    process.exit(1);
  }
  console.log(`OK: long-5000.json matches the generator (${nodes.length} nodes, ${edges.length} edges).`);
  process.exit(0);
}

writeFileSync(OUT, json);
console.log(`wrote ${OUT} — ${nodes.length} nodes, ${edges.length} edges, ${groups.length} groups.`);
